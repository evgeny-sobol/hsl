"""Orphan .txt pruning: remove generated .txt files whose source .hsl/.include
is gone. Only files whose first line is GENERATED_MARKER count as generated,
so a hand-written .txt (e.g. a full vanilla override) is never deleted.
"""
import os

GENERATED_MARKER = "# Generated by HSL from a .hsl/.include source. Do not edit by hand."


def _is_nested_checkout(dirpath, top):
    """True if dirpath is a nested git checkout inside top (e.g. a submodule).

    The top folder itself is never treated as nested, even though it usually
    contains a .git entry. Submodule checkouts carry a .git file (or dir),
    so a single existence check covers both layouts.
    """
    if os.path.realpath(dirpath) == os.path.realpath(top):
        return False
    return os.path.exists(os.path.join(dirpath, ".git"))


def _is_generated(path):
    try:
        with open(path, "r", encoding="utf-8-sig") as f:
            return f.readline().rstrip("\r\n") == GENERATED_MARKER
    except (OSError, ValueError):
        return False


def prune_orphan_txt(target_folder):
    """Delete generated .txt files that have no sibling .hsl or .include
    source. Returns the count removed."""
    removed = 0
    for root, dirs, files in os.walk(target_folder):
        # Never touch generated files inside nested checkouts (submodules).
        dirs[:] = [d for d in dirs
                   if not _is_nested_checkout(os.path.join(root, d), target_folder)]
        stems = {f.rsplit('.', 1)[0] for f in files
                 if f.endswith('.hsl') or f.endswith('.include')}
        for f in files:
            if not f.endswith('.txt') or f[:-4] in stems:
                continue
            txt_path = os.path.join(root, f)
            if not _is_generated(txt_path):
                continue
            try:
                os.remove(txt_path)
                print(f"Removed orphan: {os.path.relpath(txt_path, target_folder)}")
                removed += 1
            except OSError as e:
                print(f"  Could not remove {txt_path}: {e}")
    return removed
